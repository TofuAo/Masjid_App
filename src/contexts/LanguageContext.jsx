export const LanguageProvider = ({ children, language = 'ms' }) => {
  const [currentLanguage, setCurrentLanguage] = useState(language);

  const t = (key, params = {}) => {
    let translation = translations[currentLanguage]?.[key] || translations.ms[key] || key;
    
    // Replace parameters in translation string (e.g., {name}, {count})
    if (params && typeof translation === 'string') {
      Object.keys(params).forEach(param => {
        translation = translation.replace(new RegExp(`\\{${param}\\}`, 'g'), params[param]);
      });
    }
    
    return translation;
  };

  const changeLanguage = (lang) => {
    if (translations[lang]) {
      setCurrentLanguage(lang);
      localStorage.setItem('userLanguage', lang);
      
      // Update HTML direction for RTL languages
      if (lang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
        document.documentElement.setAttribute('lang', 'ar');
      } else {
        document.documentElement.setAttribute('dir', 'ltr');
        document.documentElement.setAttribute('lang', lang === 'ms' ? 'ms' : 'en');
      }
    }
  };

  useEffect(() => {
    // Load language from localStorage or use provided language
    const stored = localStorage.getItem('userLanguage');
    const langToUse = stored && translations[stored] ? stored : language;
    setCurrentLanguage(langToUse);
    
    // Set initial direction
    if (langToUse === 'ar') {
      document.documentElement.setAttribute('dir', 'rtl');
      document.documentElement.setAttribute('lang', 'ar');
    } else {
      document.documentElement.setAttribute('dir', 'ltr');
      document.documentElement.setAttribute('lang', langToUse === 'ms' ? 'ms' : 'en');
    }
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language: currentLanguage, t, changeLanguage }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    return { language: 'ms', t: (key, params) => key, changeLanguage: () => {} };
  }
  return context;
};

